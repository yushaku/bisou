import { captureInstallPrompt } from "./lib/install";
import { captureShortcut } from "./lib/navigation";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { ErrorBoundary } from "./components/bisou/ErrorBoundary";
import { App } from "./App";
import { Toaster } from "./components/ui/sonner";
import { I18nProvider } from "./i18n";
import { captureJoinLink } from "./lib/joinLink";
import { ThemeProvider } from "./theme/ThemeProvider";
import "./styles.css";

captureJoinLink();
captureShortcut();
captureInstallPrompt();

// Service worker (app shell cache, generated by vite-plugin-pwa) only in production builds.
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  // When a new deploy takes control, reload once so the new app shell is used.
  // Skip the first install (no previous controller), which needs no reload.
  const hadController = Boolean(navigator.serviceWorker.controller);
  let reloading = false;
  navigator.serviceWorker.addEventListener("controllerchange", () => {
    if (!hadController || reloading) return;
    reloading = true;
    window.location.reload();
  });
  window.addEventListener("load", () => {
    void navigator.serviceWorker.register("/sw.js", { scope: "/" }).then((registration) => {
      // An installed iOS app resumes without reloading, so look for a new deploy on every return.
      document.addEventListener("visibilitychange", () => {
        if (document.visibilityState === "visible") void registration.update();
      });
    });
  });
}

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <ThemeProvider>
      <I18nProvider>
        <ErrorBoundary>
          <App />
          <Toaster />
        </ErrorBoundary>
      </I18nProvider>
    </ThemeProvider>
  </StrictMode>,
);
