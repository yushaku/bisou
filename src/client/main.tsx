import { defined } from "../shared/guards";
import { captureInstallPrompt } from "./lib/install";
import { captureShortcut } from "./lib/navigation";
import { reloadOnNewVersion, watchForUpdates } from "./lib/updateReload";
import { startBoot } from "./lib/bootSession";
import { loadTabScreens } from "./lib/screens";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { ErrorBoundary } from "./components/bisou/ErrorBoundary";
import { App } from "./App";
import { OfflineNotice } from "./components/bisou/OfflineNotice";
import { Toaster } from "./components/ui/ding-toaster";
import { I18nProvider } from "./i18n";
import { captureJoinLink } from "./lib/joinLink";
import { ThemeProvider } from "./theme/ThemeProvider";
import "./styles.css";

captureJoinLink();
captureShortcut();
captureInstallPrompt();

// Service worker (app shell cache, generated by vite-plugin-pwa) only in production builds.
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  reloadOnNewVersion(navigator.serviceWorker, () => window.location.reload());
  window.addEventListener("load", () => {
    void navigator.serviceWorker
      .register("/sw.js", { scope: "/", updateViaCache: "none" })
      .then((registration) => watchForUpdates(registration))
      .catch(() => undefined);
  });
}

function mount() {
  createRoot(defined(document.getElementById("root"), "Missing #root element")).render(
    <StrictMode>
      <ThemeProvider>
        <I18nProvider>
          <ErrorBoundary>
            <App />
            <Toaster />
            <OfflineNotice />
          </ErrorBoundary>
        </I18nProvider>
      </ThemeProvider>
    </StrictMode>,
  );
}

// Boot: the device cache, /api/me, /api/couple and the Home chunk all start now, in parallel.
// With a cached session, wait briefly for the Home chunk so the first React frame is Home itself;
// the static skeleton in index.html stays on screen until then.
const boot = startBoot(loadTabScreens);
void boot.cache
  .then((cache) =>
    cache ? Promise.race([loadTabScreens(), new Promise((resolve) => setTimeout(resolve, 2000))]) : undefined,
  )
  .catch(() => undefined)
  .then(mount);
